#!/usr/bin/env python3
"""Writes src/plat/ctdata.s: the character sets X11 compound text (COMPOUND_TEXT) designates, as
Unicode, for src/plat/ctext.s. libX11 encodes a string in the first set of the locale that has each
character, so an XIM server sends Hangul as KS C 5601, kana and kanji as JIS X 0208, hanzi as
GB 2312 and accented Latin, Cyrillic or Greek as ISO 8859 halves; UTF-8 only for the rest.
  ct_96: per 96-character set, its final byte and code points for 0xa0..0xff
  ct_ksc, ct_jis, ct_gb: 94x94 code points for row and cell 0x21..0x7e (0: unassigned)
usage: tools/ctext-tables.py > src/plat/ctdata.s"""

# ESC - F designates a 96-character set into GR: final byte and Python codec
SETS_96 = [('A', 'latin_1'), ('B', 'iso8859_2'), ('C', 'iso8859_3'), ('D', 'iso8859_4'),
           ('F', 'iso8859_7'), ('G', 'iso8859_6'), ('H', 'iso8859_8'), ('L', 'iso8859_5'),
           ('M', 'iso8859_9'), ('V', 'iso8859_10'), ('Y', 'iso8859_13'), ('_', 'iso8859_14'),
           ('b', 'iso8859_15'), ('f', 'iso8859_16'), ('T', 'tis_620')]
# ESC $ ( F or ESC $ ) F designates a 94x94 set: final byte, label, EUC codec
SETS_94X94 = [('A', 'ct_gb', 'gb2312'), ('B', 'ct_jis', 'euc_jp'), ('C', 'ct_ksc', 'euc_kr')]


def char(data, codec):
    try:
        text = data.decode(codec)
    except UnicodeDecodeError:
        return 0
    return ord(text) if len(text) == 1 and ord(text) < 0x10000 else 0


def rows(label, values, per_line=16):
    out = [label + ':']
    for i in range(0, len(values), per_line):
        out.append('    .short ' + ','.join(f'0x{v:04x}' for v in values[i:i + per_line]))
    return out


def main():
    out = ['# generated by tools/ctext-tables.py: do not edit', '.section .rodata', '.p2align 1',
           '.globl ct_96, ct_96_count, ct_gb, ct_jis, ct_ksc', '# final byte, then 96 code points',
           'ct_96:']
    for final, codec in SETS_96:
        out.append(f"    .short '{final}'")
        out += rows('', [char(bytes([b]), codec) for b in range(0xa0, 0x100)])[1:]
    out.append(f'ct_96_count: .short {len(SETS_96)}')
    for final, label, codec in SETS_94X94:
        values = [char(bytes([row | 0x80, cell | 0x80]), codec)
                  for row in range(0x21, 0x7f) for cell in range(0x21, 0x7f)]
        out += rows(label, values)
    print('\n'.join(out))


if __name__ == '__main__':
    main()
